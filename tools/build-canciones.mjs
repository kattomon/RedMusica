// Builds supabase/functions/cancion/songs.js from tools/canciones.tsv.
// Usage: node tools/build-canciones.mjs   (the id of a song is its data line number, so only append new songs)
import { readFileSync, writeFileSync } from 'node:fs';

const GENRES = ['pop', 'rock', 'metal', 'hiphop', 'urbano', 'electro', 'rnb', 'disco', 'tropical', 'balada', 'folk', 'regional', 'country', 'jazz', 'tango'];
const LANGS = ['es', 'en', 'pt', 'it', 'fr', 'de', 'ko', 'ro'];
const rows = readFileSync(new URL('./canciones.tsv', import.meta.url), 'utf8').split('\n').filter(line => line.trim() && !line.startsWith('#'));
const seen = new Set();
const out = rows.map((line, index) => {
  const f = line.split('|');
  if (f.length !== 8) throw new Error(`Línea ${index + 1}: se esperaban 8 campos`);
  const [title, artists, year, country, genre, lang, kind, tier] = f.map(x => x.trim());
  if (!GENRES.includes(genre)) throw new Error(`Línea ${index + 1}: género desconocido ${genre}`);
  if (!LANGS.includes(lang)) throw new Error(`Línea ${index + 1}: idioma desconocido ${lang}`);
  if (!/^[A-Z]{2}$/.test(country) || !/^(19|20)\d\d$/.test(year) || !/^[MFG]$/.test(kind) || !/^[12]$/.test(tier)) throw new Error(`Línea ${index + 1}: datos inválidos`);
  const key = (title + '|' + artists).toLowerCase();
  if (seen.has(key)) throw new Error(`Línea ${index + 1}: canción repetida`);
  seen.add(key);
  return [index + 1, title, artists.split(';').map(a => a.trim()), Number(year), country, genre, lang, kind, Number(tier)];
});
const body = out.map(row => '  ' + JSON.stringify(row)).join(',\n');
writeFileSync(new URL('../supabase/functions/cancion/songs.js', import.meta.url),
  '// Generated by tools/build-canciones.mjs from tools/canciones.tsv. Do not edit by hand.\n' +
  '// [id, title, artists, year, country, genre, language, performer (M/F/G), tier (1 very well known, 2 known)]\n' +
  'export const SONG_ROWS = [\n' + body + '\n];\n');
console.log(`${out.length} canciones`);
